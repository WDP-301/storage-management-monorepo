import { AccessEvent } from '@entities/access-event.entity';
import { AppUser } from '@entities/app-user.entity';
import { Contract } from '@entities/contract.entity';
import { DropOffRequest } from '@entities/drop-off-request.entity';
import { Facility } from '@entities/facility.entity';
import { PickupRequest } from '@entities/pickup-request.entity';
import { ShelfReceiptLine } from '@entities/shelf-receipt-line.entity';
import { StorageUnit } from '@entities/storage-unit.entity';
import type { EvidenceFile } from '@storage/types';
import { ShelfReceiptStatus, ShelfReceiptType } from '@storage/types';
import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryGeneratedColumn,
} from 'typeorm';

/**
 * The record of one drop-off or pick-up at the counter. Never edited: a mistake is voided with a
 * reason, which reverses its stock. Shelf, warehouse and facility are snapshots, so the receipt
 * still reads right after a unit change. `sessionId` is null only for a manager's scan-less
 * recovery of an abandoned shelf.
 */
@Entity('shelf_receipts')
@Index('UQ_shelf_receipts_code', ['code'], { unique: true })
@Index('UQ_shelf_receipts_client_request', ['clientRequestId'], { unique: true })
// DESC ordering and the partial unique index are created in the migration.
@Index('IDX_shelf_receipts_contract_created', { synchronize: false })
@Index('IDX_shelf_receipts_warehouse_created', { synchronize: false })
@Index('UQ_shelf_receipts_pickup_request', { synchronize: false })
@Index('UQ_shelf_receipts_drop_off_request', { synchronize: false })
export class ShelfReceipt {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ type: 'varchar', length: 30 })
  code: string;

  @Column({ type: 'varchar', length: 10 })
  type: ShelfReceiptType;

  @Column({ type: 'varchar', length: 10, default: ShelfReceiptStatus.ACTIVE })
  status: ShelfReceiptStatus;

  @Column({ type: 'uuid', name: 'contract_id' })
  contractId: string;

  @Column({ type: 'uuid', name: 'customer_id' })
  customerId: string;

  @Column({ type: 'uuid', name: 'storage_unit_id' })
  storageUnitId: string;

  @Column({ type: 'uuid', name: 'warehouse_id' })
  warehouseId: string;

  @Column({ type: 'uuid', name: 'facility_id' })
  facilityId: string;

  @Column({ type: 'uuid', nullable: true, name: 'session_id' })
  sessionId: string | null;

  /** Generated by the app per form so a retried save returns the same receipt. */
  @Column({ type: 'uuid', name: 'client_request_id' })
  clientRequestId: string;

  @Column({ type: 'uuid', nullable: true, name: 'performed_by' })
  performedBy: string | null;

  @Column({ type: 'varchar', length: 1000, nullable: true })
  note: string | null;

  @Column({ type: 'jsonb', default: () => "'[]'" })
  photos: EvidenceFile[];

  @Column({ type: 'uuid', nullable: true, name: 'pickup_request_id' })
  pickupRequestId: string | null;

  @Column({ type: 'uuid', nullable: true, name: 'drop_off_request_id' })
  dropOffRequestId: string | null;

  @Column({ type: 'timestamptz', nullable: true, name: 'voided_at' })
  voidedAt: Date | null;

  @Column({ type: 'uuid', nullable: true, name: 'voided_by' })
  voidedBy: string | null;

  @Column({ type: 'varchar', length: 500, nullable: true, name: 'void_reason' })
  voidReason: string | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;

  @ManyToOne(() => Contract, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'contract_id' })
  contract: Contract;

  @ManyToOne(() => AppUser, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'customer_id' })
  customer: AppUser;

  @ManyToOne(() => StorageUnit, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'storage_unit_id' })
  storageUnit: StorageUnit;

  @ManyToOne(() => StorageUnit, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'warehouse_id' })
  warehouse: StorageUnit;

  @ManyToOne(() => Facility, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'facility_id' })
  facility: Facility;

  @ManyToOne(() => AccessEvent, { nullable: true, onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'session_id' })
  session: AccessEvent | null;

  @ManyToOne(() => AppUser, { nullable: true, onDelete: 'SET NULL' })
  @JoinColumn({ name: 'performed_by' })
  performer: AppUser | null;

  @ManyToOne(() => PickupRequest, { nullable: true, onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'pickup_request_id' })
  pickupRequest: PickupRequest | null;

  @ManyToOne(() => DropOffRequest, { nullable: true, onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'drop_off_request_id' })
  dropOffRequest: DropOffRequest | null;

  @ManyToOne(() => AppUser, { nullable: true, onDelete: 'SET NULL' })
  @JoinColumn({ name: 'voided_by' })
  voider: AppUser | null;

  @OneToMany(
    () => ShelfReceiptLine,
    (line) => line.receipt,
  )
  lines: ShelfReceiptLine[];
}
