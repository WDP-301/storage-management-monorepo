import { EvidenceFileDto } from '@modules/inspection/dto/inspection-evidence.dto';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { ShelfReceiptType } from '@storage/types';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsIn,
  IsInt,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  Max,
  MaxLength,
  Min,
  MinLength,
  ValidateNested,
} from 'class-validator';

export const MAX_LINE_QUANTITY = 10_000;

export class ShelfReceiptLineDto {
  @ApiPropertyOptional({
    format: 'uuid',
    description: 'An item already on the shelf (top up / take)',
  })
  @IsOptional()
  @IsUUID('all')
  itemId?: string;

  @ApiPropertyOptional({
    maxLength: 120,
    description:
      'Drop-off only: a name; matches an existing item case-insensitively, else a new item',
  })
  @IsOptional()
  @IsString()
  @MaxLength(300)
  name?: string;

  @ApiProperty({ minimum: 1, maximum: MAX_LINE_QUANTITY })
  @IsInt()
  @Min(1)
  @Max(MAX_LINE_QUANTITY)
  quantity: number;
}

export class CreateShelfReceiptDto {
  @ApiProperty({
    format: 'uuid',
    description: 'Generated by the app per form; a replay returns the same receipt',
  })
  @IsUUID('all')
  clientRequestId: string;

  @ApiProperty({ format: 'uuid' })
  @IsUUID('all')
  sessionId: string;

  @ApiProperty({ format: 'uuid' })
  @IsUUID('all')
  contractId: string;

  @ApiProperty({ enum: Object.values(ShelfReceiptType) })
  @IsIn(Object.values(ShelfReceiptType))
  type: ShelfReceiptType;

  @ApiProperty({ type: [ShelfReceiptLineDto], minItems: 1, maxItems: 50 })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(50)
  @ValidateNested({ each: true })
  @Type(() => ShelfReceiptLineDto)
  lines: ShelfReceiptLineDto[];

  @ApiPropertyOptional({
    type: [EvidenceFileDto],
    maxItems: 10,
    description: 'Own uploads only. Required (1..10) for DROP_OFF',
  })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(10)
  @ValidateNested({ each: true })
  @Type(() => EvidenceFileDto)
  photos?: EvidenceFileDto[];

  @ApiPropertyOptional({ maxLength: 1000 })
  @IsOptional()
  @IsString()
  @MaxLength(1000)
  note?: string;

  @ApiPropertyOptional({
    format: 'uuid',
    description: 'PICK_UP only: the contract open request it completes',
  })
  @IsOptional()
  @IsUUID('all')
  pickupRequestId?: string;
}

export class VoidShelfReceiptDto {
  @ApiProperty({ minLength: 3, maxLength: 500, example: 'Nhập nhầm số lượng' })
  @IsString()
  @MinLength(3)
  @MaxLength(500)
  @Matches(/\S/, { message: 'reason must not be blank' })
  reason: string;
}
