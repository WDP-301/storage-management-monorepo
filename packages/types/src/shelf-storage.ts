import type {
  ContractStatus,
  PickupRequestStatus,
  ShelfReceiptStatus,
  ShelfReceiptType,
} from './domain.enums';
import type { PaginationMeta } from './index';
import type { EvidenceFile } from './return-request';
import type { ShelfDisputeTicketRef } from './shelf-records';

// Staff-managed shelf storage: counter sessions, drop-off / pick-up receipts, pick-up requests.
// Dates arrive as ISO strings.

export interface ShelfRef {
  id: string;
  code: string;
  name: string;
}
export interface ShelfPersonRef {
  id: string;
  fullName: string | null;
  phone: string | null;
}
export interface ShelfStaffRef {
  id: string;
  fullName: string;
}
export interface ShelfItemView {
  id: string;
  name: string;
  quantity: number;
  updatedAt: string | Date;
}

export type DropOffBlockReason = 'CONTRACT_NOT_STARTED' | 'INVOICE_OVERDUE';
export type PickUpBlockReason = 'NO_STOCK' | 'INVOICE_OVERDUE';
export type PickupRequestBlockReason =
  | 'CONTRACT_NOT_ACTIVE'
  | 'OPEN_REQUEST_EXISTS'
  | 'NO_STOCK'
  | 'INVOICE_OVERDUE';

export interface ShelfReceiptLineView {
  itemId: string;
  name: string;
  quantity: number;
}

export interface ShelfReceiptView {
  /** PG-YYYYMMDD-XXXXXXXX (drop-off) or PL-… (pick-up), Vietnam date. */
  id: string;
  code: string;
  type: ShelfReceiptType;
  status: ShelfReceiptStatus;
  contractId: string;
  contractNo: string;
  /** Shelf, warehouse and facility as they were when the receipt was saved. */
  shelf: ShelfRef;
  warehouse: ShelfRef;
  facility: ShelfRef;
  customer: ShelfPersonRef;
  performedBy: ShelfStaffRef | null;
  createdAt: string | Date;
  note: string | null;
  photos: EvidenceFile[];
  lines: ShelfReceiptLineView[];
  pickupRequestId: string | null;
  /** A manager's scan-less pick-up on an abandoned return. */
  recovered: boolean;
  void: { at: string | Date; by: ShelfStaffRef | null; reason: string } | null;
  /** Newest open service ticket the customer filed about this receipt; null = none open. */
  openDisputeTicket: ShelfDisputeTicketRef | null;
}

/** An open RETURN with source ABANDONED and goods still on the shelf. */
export interface AbandonedShelfContractView {
  contractId: string;
  contractNo: string;
  shelf: ShelfRef;
  customer: ShelfPersonRef;
  returnScheduledAt: string | Date;
  items: ShelfItemView[];
}

export interface PickupRequestLineView {
  itemId: string;
  name: string;
  quantity: number;
  /** Current stock of the item. */
  available: number;
}

export interface PickupRequestView {
  id: string;
  status: PickupRequestStatus;
  contractId: string;
  contractNo: string;
  shelf: ShelfRef;
  warehouse: ShelfRef;
  customer: ShelfPersonRef;
  requestedFor: string | Date;
  note: string | null;
  lines: PickupRequestLineView[];
  createdAt: string | Date;
  readyAt: string | Date | null;
  readyBy: ShelfStaffRef | null;
  cancelledAt: string | Date | null;
  cancelledBy: 'CUSTOMER' | 'SYSTEM' | null;
  completedAt: string | Date | null;
  completedReceiptId: string | null;
}

export interface CounterContractView {
  contractId: string;
  contractNo: string;
  effectiveAt: string | Date;
  shelf: ShelfRef;
  /** A RETURN inspection exists and is not finalized. */
  returnOpen: boolean;
  /** Null = allowed now. */
  dropOff: DropOffBlockReason | null;
  pickUp: PickUpBlockReason | null;
  /** Quantity > 0 only, name ascending. */
  items: ShelfItemView[];
  openRequest: PickupRequestView | null;
  /** Newest 5 of this contract. */
  recentReceipts: ShelfReceiptView[];
}

export interface CounterSessionView {
  sessionId: string;
  startedAt: string | Date;
  /** startedAt + 30 minutes. */
  expiresAt: string | Date;
  /** Whole seconds left when this response was built; clients count down from it, not from their clock. */
  ttlSeconds: number;
  warehouse: ShelfRef;
  facility: ShelfRef;
  customer: ShelfPersonRef;
  overdueInvoiceNos: string[];
  /** The customer's ACTIVE shelf contracts in this warehouse. */
  contracts: CounterContractView[];
}

export interface ShelfContractStorageView {
  contractId: string;
  contractNo: string;
  contractStatus: ContractStatus;
  shelf: ShelfRef;
  warehouse: ShelfRef;
  items: ShelfItemView[];
  openRequest: PickupRequestView | null;
  /** Null = the customer may create a request now. */
  pickupRequestBlock: PickupRequestBlockReason | null;
}

export interface ShelfReceiptPage {
  receipts: ShelfReceiptView[];
  meta: PaginationMeta;
}

export interface OpenCounterSessionInput {
  qrPayload: string;
  warehouseId: string;
}

export interface ShelfReceiptLineInput {
  itemId?: string;
  name?: string;
  quantity: number;
}

export interface CreateShelfReceiptInput {
  /** Generated by the app per form; a replay returns the same receipt. */
  clientRequestId: string;
  sessionId: string;
  contractId: string;
  type: ShelfReceiptType;
  /** 1..50. */
  lines: ShelfReceiptLineInput[];
  /** Own uploads only; DROP_OFF 1..10 (required), PICK_UP 0..10. */
  photos?: EvidenceFile[];
  /** At most 1000 characters. */
  note?: string;
  /** PICK_UP only; must be the contract's open request. */
  pickupRequestId?: string;
}

export interface PickupRequestLineInput {
  itemId: string;
  quantity: number;
}

/** A scan-less PICK_UP on an abandoned return. */
export interface CreateShelfRecoveryInput {
  clientRequestId: string;
  contractId: string;
  /** 1..50. */
  lines: PickupRequestLineInput[];
  /** 1..10, own uploads only. */
  photos: EvidenceFile[];
  /** Required, not blank, at most 1000 characters. */
  note: string;
}

/** Reason is 3..500 characters, not blank. */
export interface VoidShelfReceiptInput {
  reason: string;
}

export interface CreatePickupRequestInput {
  lines: PickupRequestLineInput[];
  requestedFor: string;
  note?: string;
}
