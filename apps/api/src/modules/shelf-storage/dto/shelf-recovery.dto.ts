import { EvidenceFileDto } from '@modules/inspection/dto/inspection-evidence.dto';
import { ApiProperty } from '@nestjs/swagger';
import { Transform, Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsInt,
  IsString,
  IsUUID,
  Matches,
  Max,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';
import { MAX_LINE_QUANTITY } from './shelf-receipt.dto';

export class RecoveryLineDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID('all')
  itemId: string;

  @ApiProperty({ minimum: 1, maximum: MAX_LINE_QUANTITY })
  @IsInt()
  @Min(1)
  @Max(MAX_LINE_QUANTITY)
  quantity: number;
}

export class CreateShelfRecoveryDto {
  @ApiProperty({
    format: 'uuid',
    description: 'Generated by the app per form; a replay returns the same receipt',
  })
  @IsUUID('all')
  clientRequestId: string;

  @ApiProperty({ format: 'uuid' })
  @IsUUID('all')
  contractId: string;

  @ApiProperty({ type: [RecoveryLineDto], minItems: 1, maxItems: 50 })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(50)
  @ValidateNested({ each: true })
  @Type(() => RecoveryLineDto)
  lines: RecoveryLineDto[];

  @ApiProperty({
    type: [EvidenceFileDto],
    minItems: 1,
    maxItems: 10,
    description: 'Own uploads only',
  })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(10)
  @ValidateNested({ each: true })
  @Type(() => EvidenceFileDto)
  photos: EvidenceFileDto[];

  @ApiProperty({ maxLength: 1000, example: 'Khách bỏ kệ, đã gọi 3 lần không liên lạc được' })
  @Transform(({ value }) => (typeof value === 'string' ? value.trim() : value))
  @IsString()
  @Matches(/\S/, { message: 'note must not be blank' })
  @MaxLength(1000)
  note: string;
}
